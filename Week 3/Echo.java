// the class definition is a block
public class Echo {

    // ...as is the main() entry point method
    public static void main(String[] args) {

        // ...as is the conditional statement!
        if (args.length >= 1) {
            System.out.println(args[0]);
        }
        else {
            System.out.println("I need to see an argument");
        }
    }
}